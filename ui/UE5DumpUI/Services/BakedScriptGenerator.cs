using System.Globalization;
using System.Text;
using UE5DumpUI.Models;

namespace UE5DumpUI.Services;

/// <summary>
/// Generates a non-interactive CE AA Script that invokes a UFunction with
/// pre-baked argument values. Designed for redistribution as part of a
/// Cheat Engine table -- the user enables the script and the function
/// fires once with the baked values, no UI interaction needed.
///
/// The generated script depends on <c>ue5_invoke_helper.lua</c> being
/// embedded in the same .CT via Table -> Add File... (see
/// <see cref="HelperFileResource"/> for the export action). At runtime the
/// script uses <c>findTableFile</c> to locate the helper and calls
/// <c>invokeUFunction</c> with the baked params table.
///
/// Sister to <see cref="InvokeScriptGenerator"/>:
/// <list type="bullet">
/// <item>InvokeScriptGenerator builds an in-CE form so the user fills
///     values at runtime in CE.</item>
/// <item>BakedScriptGenerator inlines the values at generation time and
///     produces a script ~5x smaller; the user fills values in the
///     UE5DumpUI dialog, then ships a static AA Script.</item>
/// </list>
/// Both use single-quoted Lua strings so the output transmits cleanly
/// through the AOBMaker JSON pipe.
/// </summary>
public static class BakedScriptGenerator
{
    /// <summary>Stable name of the embedded helper file the generated
    /// script will look up via <c>findTableFile</c>.</summary>
    public const string HelperFileName = "ue5_invoke_helper.lua";

    /// <summary>
    /// Generate a complete CE AA Script that invokes <paramref name="funcName"/>
    /// on a live instance of <paramref name="className"/> with the supplied
    /// baked parameter values.
    /// </summary>
    /// <param name="className">UClass name (e.g. "PlayerCharacter"). The
    ///     helper's CMD_INVOKE_BY_NAME path will <c>findInstance</c> live
    ///     non-CDO objects matching this name.</param>
    /// <param name="funcName">UFunction name (e.g. "AddMoney").</param>
    /// <param name="parmsSize">Total size of the function's params buffer
    ///     in bytes. The helper zero-fills this range before writing baked
    ///     values, so unsupplied params (e.g. return slot) start clean.</param>
    /// <param name="bakedValues">Param values to write. Pass an empty list
    ///     for void-return / no-arg functions; the generator will still
    ///     emit a clean invoke call.</param>
    /// <returns>A self-contained AA Script string with [ENABLE]/[DISABLE]
    ///     blocks. Trailing LF only (no CR) for CE compatibility.</returns>
    public static string Generate(
        string className,
        string funcName,
        int parmsSize,
        IReadOnlyList<BakedParamValue> bakedValues,
        BakedParamValue? returnParam = null,
        bool verifyReturn = false)
    {
        var sb = new StringBuilder(4096);

        Line(sb, "[ENABLE]");
        Line(sb, "{$lua}");
        Line(sb, "if syntaxcheck then return end");
        CeLuaHygiene.AppendDebugPreamble(sb);
        Line(sb, "-- ================================================================");
        Line(sb, $"-- UFunction Invoker (baked args): {className}::{funcName}");
        Line(sb, $"-- Generated by UE5CEDumper | {CeLuaHygiene.AttributionUrl}");
        Line(sb, "--");
        Line(sb, "-- REQUIREMENT: ue5_invoke_helper.lua MUST be embedded in this");
        Line(sb, "-- table via 'Table -> Add File...' (one-time setup per .CT).");
        Line(sb, "-- Get the file from UE5DumpUI: Tools -> Export CE Helper Lua File...");
        Line(sb, "-- ================================================================");
        Line(sb);

        // Helper loader -- no filesystem fallback; explicit error on missing.
        AppendHelperLoader(sb);

        // Baked params table (or empty marker for no-arg functions)
        AppendBakedParamsTable(sb, bakedValues);

        // Invoke + result handling (silent on success, print + showMessage on error;
        // when verifyReturn is set, emits a diagnostic block instead).
        AppendInvokeAndResultHandler(sb, className, funcName, parmsSize,
                                     returnParam, verifyReturn);

        // Auto-disable + close lua engine on success (your hygiene rule).
        // Verify-return mode keeps the engine open so the diagnostic print
        // remains readable -- the close branch is conditionally suppressed.
        AppendCleanupAndClose(sb, keepEngineOpen: verifyReturn);

        Line(sb, "{$asm}");
        Line(sb, "[DISABLE]");
        Line(sb, "{$lua}");
        Line(sb, "-- nop");
        Line(sb, "{$asm}");

        return sb.ToString();
    }

    // ------------------------------------------------------------------
    // Section emitters
    // ------------------------------------------------------------------

    /// <summary>Emit the standard "load ue5_invoke_helper.lua from the embedded
    /// table file" preamble (no filesystem fallback). Public so sibling
    /// generators (e.g. <see cref="DebugCameraScriptGenerator"/>) reuse the
    /// exact, proven loader instead of duplicating it.</summary>
    public static void AppendHelperLoader(StringBuilder sb)
    {
        Line(sb, "-- Load helper from embedded table file (NO filesystem fallback)");
        Line(sb, $"local tf = findTableFile('{HelperFileName}')");
        Line(sb, "if not tf then");
        Line(sb, "  showMessage(");
        Line(sb, $"    '[Invoke] {HelperFileName} not found in this table.\\n\\n' ..");
        Line(sb, $"    'Setup: Table -> Add File... -> select {HelperFileName}\\n' ..");
        Line(sb, "    '(Export it from UE5DumpUI: Tools -> Export CE Helper Lua File)')");
        Line(sb, "  if memrec then memrec.Active = false end");
        Line(sb, "  return");
        Line(sb, "end");
        Line(sb, "do");
        Line(sb, "  local ss = createStringStream()");
        Line(sb, "  ss.copyFrom(tf.Stream, tf.Stream.Size)");
        Line(sb, "  local fn, err = load(ss.DataString)");
        Line(sb, "  ss.destroy()");
        Line(sb, "  if not fn then");
        Line(sb, "    showMessage('[Invoke] Helper load error:\\n' .. tostring(err))");
        Line(sb, "    if memrec then memrec.Active = false end");
        Line(sb, "    return");
        Line(sb, "  end");
        Line(sb, "  fn()");
        Line(sb, "end");
        Line(sb);
    }

    private static void AppendBakedParamsTable(
        StringBuilder sb, IReadOnlyList<BakedParamValue> values)
    {
        if (values.Count == 0)
        {
            Line(sb, "-- (no input params -- direct invoke)");
            Line(sb, "local PARAMS = {}");
            Line(sb);
            return;
        }

        Line(sb, "-- ====== BAKED PARAMS (edit values here) ==============================");
        Line(sb, "local PARAMS = {");
        foreach (var v in values)
        {
            // Input path uses MapInputType so string params keep their wide/
            // narrow distinction ('fstring' vs 'fstringn') the helper needs.
            // v.Size was in hand here the whole time and used only by the 'fstruct'
            // arm below; an EnumProperty needs it too or it is written as 4 bytes
            // over the next param (audit #5 Y16 site 2).
            var helperType = MapInputType(v.UeTypeName, v.Size);
            var literal = RenderLiteral(v.UeTypeName, v.LiteralText);
            // By-value struct ('fstruct'): emit the exact byte size so the
            // helper zeroes the right region instead of falling back to its
            // fragile next-offset-difference heuristic (the params list is in
            // declaration order, not sorted by offset).
            var sizeField = helperType == "fstruct" ? $"size={v.Size}, " : "";
            // Each row: { name='...', type='...', offset=N, [size=N,] value=LITERAL },  -- shortType
            Line(sb,
                $"  {{ name='{EscapeLua(v.ParamName)}', type='{helperType}', " +
                $"offset={v.Offset}, {sizeField}value={literal} }},  " +
                $"-- {ShortTypeNameForComment(v.UeTypeName, v.Size)} {v.Size}B");
        }
        Line(sb, "}");
        Line(sb, "-- =====================================================================");
        Line(sb);
    }

    private static void AppendInvokeAndResultHandler(
        StringBuilder sb, string className, string funcName, int parmsSize,
        BakedParamValue? returnParam, bool verifyReturn)
    {
        // Verify mode: emit a Before/After raw-byte dump around the invoke
        // so the user can distinguish "function didn't run" (After == Before)
        // from "wrong return offset" (return value lands somewhere else).
        // The dump covers the smaller of (parmsSize, 32) bytes -- enough for
        // typical 1-2 input + 1 return functions without flooding the output.
        if (verifyReturn)
        {
            Line(sb, "-- ====== Verify mode: dump params buffer + decoded return ======");
            Line(sb, "-- Resolve mailbox via getAddressSafe + module-prefixed fallback,");
            Line(sb, "-- mirroring the helper's findMailbox(). Bare getAddress() is fine");
            Line(sb, "-- in some setups but throws / returns garbage in others when CE's");
            Line(sb, "-- symbol resolver only registers the prefixed form -- without this");
            Line(sb, "-- guard the dump call would later hit string.format with nil.");
            Line(sb, "local _mb_dbg = (function()");
            Line(sb, "  local a = getAddressSafe('g_invokeMailbox')");
            Line(sb, "  if not a or a == 0 then a = getAddressSafe('UE5Dumper.g_invokeMailbox') end");
            Line(sb, "  return a or 0");
            Line(sb, "end)()");
            Line(sb, $"local _PD_dbg = _mb_dbg + (UE5_INVOKE_PARAMS_OFFSET or 0x328)");
            int dumpLen = Math.Max(8, Math.Min(parmsSize, 32));
            Line(sb, $"local _DUMP_LEN = {dumpLen}  -- min(parmsSize, 32)");
            Line(sb, "local function _dumpHex(label)");
            Line(sb, "  if _mb_dbg == 0 then");
            Line(sb, "    print(label .. ': <mailbox unresolved -- is UE5Dumper.dll injected?>')");
            Line(sb, "    return");
            Line(sb, "  end");
            Line(sb, "  local s = label .. ': '");
            Line(sb, "  for i = 0, _DUMP_LEN - 1 do");
            // `or 0` keeps the dump alive even if readByte returns nil for a
            // single byte (e.g. half-page boundary on a tiny region) -- shows
            // 00 instead of crashing the whole script.
            Line(sb, "    s = s .. string.format('%02X ', readByte(_PD_dbg + i) or 0)");
            Line(sb, "  end");
            Line(sb, "  print(s)");
            Line(sb, "end");
            // Wipe the params buffer to parmsSize BEFORE the Before dump.
            // The mailbox is a single shared buffer reused across every
            // invoke in this CE session -- the DLL has no clean transition
            // point to zero it after a call (would race with Lua reading
            // the return value), and the helper's writeBakedParams zero
            // happens AFTER this dump. Without this pre-zero, the Before
            // dump shows leftover bytes from the previous invoke (e.g.
            // ES2 / Geri 2026-05-11 test: scen 2's Before showed scen 1's
            // [3, 4, 7] payload). Pre-zeroing here makes Before always
            // appear clean, so Before vs After unambiguously isolates
            // what THIS invoke wrote.
            Line(sb, "if _mb_dbg ~= 0 then");
            Line(sb, $"  for i = 0, {parmsSize} - 1 do writeByte(_PD_dbg + i, 0) end");
            Line(sb, "end");
            Line(sb, "_dumpHex('[Invoke] Before')");
            Line(sb);
        }

        Line(sb, verifyReturn
            ? "-- Invoke (verify mode -- prints decoded return value on success)"
            : "-- Invoke (silent on success -- only prints/showMessage on error)");
        Line(sb,
            $"local ok, err = invokeUFunction('{EscapeLua(className)}', " +
            $"'{EscapeLua(funcName)}', {parmsSize}, PARAMS)");

        if (verifyReturn)
        {
            Line(sb, "_dumpHex('[Invoke] After ')");
            Line(sb, "if ok then");
            if (returnParam != null)
            {
                var displayType = MapToHelperType(returnParam.UeTypeName, returnParam.Size);
                // The helper's readUFunctionReturn doesn't recognise 'pointer'
                // (defaults to int32 = 4-byte read on the 8-byte pointer slot).
                // Send 'qword' on the wire while showing 'pointer' in the
                // human-readable label so the user still sees the UE-side type.
                var readType = displayType == "pointer" ? "qword" : displayType;
                var fmt = ReturnPrintFormat(returnParam.UeTypeName);

                if (IsComplexReturnType(returnParam.UeTypeName))
                {
                    // FString / FText / TArray / TMap / TSet / FStruct etc. are
                    // multi-byte buffer layouts the helper has no decoder for.
                    // Print just the raw decoded label and tell the user to
                    // read the After: dump for the actual bytes -- still useful
                    // ("ReturnValue is non-zero in the dump → function ran").
                    Line(sb,
                        $"  print('[Invoke] OK: {EscapeLua(className)}::{EscapeLua(funcName)} " +
                        $"-> {EscapeLua(returnParam.ParamName)} ({displayType}@{returnParam.Offset}, " +
                        $"size={returnParam.Size}B) -- complex return; see After: dump above')");
                }
                else
                {
                    Line(sb,
                        $"  local _ret = readUFunctionReturn({returnParam.Offset}, '{readType}')");
                    Line(sb,
                        $"  print(string.format('[Invoke] OK: {EscapeLua(className)}::{EscapeLua(funcName)} " +
                        $"-> {EscapeLua(returnParam.ParamName)} ({displayType}@{returnParam.Offset}) = " +
                        $"{fmt}', _ret))");
                }
            }
            else
            {
                // Void-return: still confirm the call completed.
                Line(sb,
                    $"  print('[Invoke] OK: {EscapeLua(className)}::{EscapeLua(funcName)} " +
                    "(void return)')");
            }
            Line(sb, "else");
            Line(sb, "  print(string.format('[Invoke] FAILED: %s::%s -- %s',");
            Line(sb, $"                      '{EscapeLua(className)}', " +
                      $"'{EscapeLua(funcName)}', tostring(err)))");
            Line(sb, "  showMessage('Invoke failed:\\n' .. tostring(err))");
            Line(sb, "end");
        }
        else
        {
            Line(sb, "if not ok then");
            Line(sb, "  print(string.format('[Invoke] FAILED: %s::%s -- %s',");
            Line(sb, $"                      '{EscapeLua(className)}', " +
                      $"'{EscapeLua(funcName)}', tostring(err)))");
            Line(sb, "  showMessage('Invoke failed:\\n' .. tostring(err))");
            Line(sb, "end");

            // DEBUG-only return-value print (verify mode already prints its own,
            // richer diagnostic, so this only fires in the non-verify path).
            // Quiet by default; when UE5_DEBUG=1 the value is printed and the
            // window is kept open (the success-close is DEBUG==0-gated). The
            // helper's mailbox is resolved here (getAddressSafe + module-prefixed
            // fallback, mirroring findMailbox) so the raw slot can be read.
            if (returnParam != null &&
                returnParam.Offset >= 0 &&
                (parmsSize <= 0 || returnParam.Offset < parmsSize))
            {
                Line(sb, "if ok and DEBUG ~= 0 then");
                Line(sb, "  local _mbret = getAddressSafe('g_invokeMailbox')");
                Line(sb, "  if not _mbret or _mbret == 0 then _mbret = getAddressSafe('UE5Dumper.g_invokeMailbox') end");
                Line(sb, "  if _mbret and _mbret ~= 0 then");
                Line(sb, "    local _PDret = _mbret + (UE5_INVOKE_PARAMS_OFFSET or 0x328)");
                CeInvokeReturn.AppendDecodeAndPrint(sb, className, funcName,
                    returnParam.ParamName, returnParam.UeTypeName,
                    returnParam.Size, returnParam.Offset, "_PDret", "    ");
                Line(sb, "  end");
                Line(sb, "end");
            }
        }
        Line(sb);
    }

    private static void AppendCleanupAndClose(StringBuilder sb, bool keepEngineOpen)
    {
        Line(sb, "-- Auto-disable memrec; on success also close the lua engine window.");
        Line(sb, "-- (Errors leave the window open so you can read the message.)");
        Line(sb, "local t = createTimer(nil, false)");
        Line(sb, "t.Interval = 100");
        Line(sb, "t.OnTimer = function(s)");
        Line(sb, "  s.Enabled = false");
        Line(sb, "  s.destroy()");
        Line(sb, "  if memrec then memrec.Active = false end");
        if (keepEngineOpen)
        {
            // Verify mode: leave the engine window open so the user can
            // read the Before/After dump and the decoded return print.
            Line(sb, "  -- (verify mode: engine window kept open so you can read the diagnostic)");
        }
        else
        {
            // Close on success ONLY when DEBUG is off -- if the user set UE5_DEBUG=1
            // they want the window (and any dbg output) to stay readable.
            Line(sb, "  if ok and DEBUG == 0 then");
            Line(sb, "    synchronize(function() getLuaEngine().Close() end)");
            Line(sb, "  end");
        }
        Line(sb, "end");
        Line(sb, "t.Enabled = true");
        Line(sb);
    }

    /// <summary>
    /// Pick a <c>string.format</c> specifier for the decoded return value
    /// based on UE type. Doubles/floats use <c>%.10g</c> (matches the
    /// diagnostic snippet documented in the dev guide); pointer-shaped
    /// types render as 0x%X; ints render as %d.
    /// </summary>
    private static string ReturnPrintFormat(string ueTypeName) => ueTypeName switch
    {
        "DoubleProperty" or "FloatProperty"           => "%.10g",
        "ObjectProperty" or "ClassProperty" or "NameProperty"
            or "SoftObjectProperty" or "SoftClassProperty"
            or "WeakObjectProperty" or "LazyObjectProperty"
            or "InterfaceProperty" or "UInt64Property" => "0x%X",
        "BoolProperty"                                 => "%d",
        _                                              => "%d",
    };

