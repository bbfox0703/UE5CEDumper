    /// <summary>
    /// Map a UE FProperty type name to the helper-recognised type token
    /// (see <c>writeBakedParams</c> in scripts/ue5_invoke_helper.lua).
    /// </summary>
    /// <remarks>
    /// All pointer-shaped types (object/class/name/soft/weak/lazy/interface/
    /// uint64) collapse to <c>'pointer'</c>; the helper writes them as a
    /// qword. Unrecognised types fall through to <c>'int32'</c> and the
    /// generator stamps a TODO in the literal so the user notices.
    /// </remarks>
    /// <param name="size">
    /// Engine-reported byte width, used ONLY by <c>EnumProperty</c> (audit #5 Y16).
    /// UE sizes an enum by its underlying type -- 1 byte for the common
    /// TEnumAsByte / <c>enum class : uint8</c> -- so the old flat <c>'int32'</c>
    /// wrote 4 bytes and clobbered the next parameter. 0 (the sizeless overload)
    /// keeps the historical 4-byte answer.
    ///
    /// <para>Only enums consult it, deliberately: every other type's width is
    /// implied by its name, and letting <c>size</c> override those would turn a
    /// mis-reported size into a wrong write for types that are currently correct.
    /// <c>MapToHelperTypeIgnoresSizeForEveryTypeButEnum</c> pins that.</para>
    ///
    /// <para>No Lua change is needed: <c>writeBakedParams</c> already accepts the
    /// <c>byte</c> / <c>int16</c> / <c>int64</c> tokens, so nobody has to re-embed
    /// the helper.</para>
    /// </param>
    /// <summary>
    /// Size-less overload. Every type whose width is fixed by its NAME maps
    /// identically; <c>EnumProperty</c> — the one type whose width is not — falls back
    /// to the legacy <c>int32</c>. Callers holding a real param should pass its size.
    /// Same shape as <c>FreezeScriptGenerator.MapToHelperType</c>, which Y15 built.
    /// </summary>
    public static string MapToHelperType(string ueTypeName)
        => MapToHelperType(ueTypeName, 0);

    public static string MapToHelperType(string ueTypeName, int size) => ueTypeName switch
    {
        "BoolProperty"                                => "bool",
        "ByteProperty" or "Int8Property"              => "byte",
        "Int16Property" or "UInt16Property"           => "int16",
        "IntProperty" or "UInt32Property"             => "int32",
        // Whatever the engine reported, never implied by the name -- the same rule
        // ParamBufferBuilder.EffectiveIntWidth already applies on the FIRE path.
        "EnumProperty"                                => size switch
        {
            1 => "byte",
            2 => "int16",
            8 => "int64",
            _ => "int32",
        },
        "Int64Property"                               => "int64",
        "UInt64Property"                              => "pointer",
        "FloatProperty"                               => "float",
        "DoubleProperty"                              => "double",
        "ObjectProperty" or "ClassProperty" or "NameProperty"
            or "SoftObjectProperty" or "SoftClassProperty"
            or "WeakObjectProperty" or "LazyObjectProperty"
            or "InterfaceProperty"                    => "pointer",
        // Complex multi-byte buffer types -- the helper has no scalar
        // decoder for these, so the verify-mode emit treats them as a
        // raw region (size taken from the param) and tells the user to
        // read the After: hex dump. Still better than silently falling
        // through to int32 and reading 4 random bytes.
        // FString + UE5.5+ FUtf8String / FAnsiString: all multi-byte buffer types the
        // helper can't scalar-decode (treated as a raw region → "see hex dump" hint).
        // Without these arms the new variants fall to the int32 default and mis-read 4
        // bytes of the string header.
        "StrProperty" or "Utf8StrProperty" or "AnsiStrProperty" => "fstring",
        "TextProperty"                                => "ftext",
        "ArrayProperty"                               => "tarray",
        "MapProperty"                                 => "tmap",
        "SetProperty"                                 => "tset",
        "StructProperty"                              => "fstruct",
        "DelegateProperty" or "MulticastDelegateProperty"
            or "MulticastInlineDelegateProperty"
            or "MulticastSparseDelegateProperty"      => "delegate",
        _                                             => "int32",
    };

    /// <summary>
    /// Map a UE FProperty type to the helper token used when <b>writing an
    /// input</b> param. Identical to <see cref="MapToHelperType"/> except
    /// string types keep their wide/narrow distinction — <c>StrProperty</c>
    /// stays <c>'fstring'</c> (UTF-16) while <c>Utf8StrProperty</c>/
    /// <c>AnsiStrProperty</c> become <c>'fstringn'</c> (raw bytes) — because
    /// the helper needs it to build the right char buffer. The return-value
    /// path keeps calling <see cref="MapToHelperType"/> (which collapses all
    /// three to <c>'fstring'</c>) so its complex-type classification is
    /// unaffected.
    /// </summary>
    public static string MapInputType(string ueTypeName)
        => MapInputType(ueTypeName, 0);

    /// <summary>Size-aware form — this is the WRITE path, so an enum reaching it with
    /// the wrong width corrupts the next parameter (audit #5 Y16 site 2).</summary>
    public static string MapInputType(string ueTypeName, int size) => ueTypeName switch
    {
        "StrProperty"                          => "fstring",
        "Utf8StrProperty" or "AnsiStrProperty" => "fstringn",
        _                                      => MapToHelperType(ueTypeName, size),
    };

    /// <summary>
    /// True for types the helper's <c>readUFunctionReturn</c> can't decode
    /// as a single scalar -- caller emits a "see hex dump" hint instead
    /// of an actual read+print line. Keeps the diagnostic honest rather
    /// than printing a misleading 4-byte slice of an FString header.
    /// </summary>
    public static bool IsComplexReturnType(string ueTypeName)
    {
        var t = MapToHelperType(ueTypeName);
        return t is "fstring" or "ftext" or "tarray" or "tmap"
                 or "tset" or "fstruct" or "delegate";
    }

    /// <summary>
    /// Render a user-entered text value as a Lua numeric literal, picking
    /// the encoding (decimal int, decimal float, hex) by UE type. Falls
    /// back to a parenthesised raw expression with a TODO comment marker
    /// when parsing fails -- the generator never silently mangles input.
    /// </summary>
    public static string RenderLiteral(string ueTypeName, string text)
    {
        // String types render as a quoted Lua string literal (helper reads
        // p.value as the text and builds the FString). An empty value is a
        // valid empty string, not the numeric 0 fallback.
        if (ueTypeName is "StrProperty" or "Utf8StrProperty" or "AnsiStrProperty")
            return "'" + EscapeLua(text ?? "") + "'";

        var t = (text ?? "").Trim();
        if (t.Length == 0) return "0";

        // Pointer-shaped types: prefer hex form
        if (ueTypeName is "ObjectProperty" or "ClassProperty" or "NameProperty"
            or "SoftObjectProperty" or "SoftClassProperty"
            or "WeakObjectProperty" or "LazyObjectProperty"
            or "InterfaceProperty" or "UInt64Property" or "Int64Property")
        {
            if (TryParseHexOrDecimal(t, out ulong u))
            {
                // Emit zero as plain "0" for readability; non-zero as 0xHEX
                return u == 0 ? "0" : $"0x{u:X}";
            }
            return MarkUnparsed(t);
        }

        // Bool: accept true/false/0/1/yes/no
        if (ueTypeName == "BoolProperty")
        {
            return ParseBoolLiteral(t) is { } b ? (b ? "1" : "0") : MarkUnparsed(t);
        }

        // Float / double: prefer InvariantCulture decimal
        if (ueTypeName is "FloatProperty" or "DoubleProperty")
        {
            // IsFinite is not belt-and-braces here. double.TryParse ACCEPTS "NaN",
            // "Infinity" and "-Infinity" (and overflowing literals round to ±Infinity),
            // so the parse "succeeds" and MarkUnparsed never fires — then ToString("R")
            // emits those bare words, which are not Lua number literals. Lua reads them
            // as an undefined global, i.e. `nil`, and the baked param silently becomes
            // nothing at all. Input is unvalidated upstream (InvokeParamDialog). (B23)
            if (double.TryParse(t, NumberStyles.Float, CultureInfo.InvariantCulture, out var d)
                && double.IsFinite(d))
            {
                return d.ToString("R", CultureInfo.InvariantCulture);
            }
            return MarkUnparsed(t);
        }

        // Integer scalars (incl. enum/byte/int16): allow decimal or 0x form.
        // Emit as signed-decimal so negative values round-trip naturally; the
        // helper's writeBakedParams uses math.floor on the value so any
        // accidental fraction would be silently truncated upstream anyway.
        if (TryParseHexOrDecimal(t, out ulong i))
        {
            // If the user wrote 0x..., preserve the hex form for readability;
            // otherwise stick to decimal so negative inputs read naturally.
            if (t.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
                return $"0x{i:X}";
            return unchecked((long)i).ToString(CultureInfo.InvariantCulture);
        }
        return MarkUnparsed(t);
    }

    private static string MarkUnparsed(string raw)
        => $"--[[unparsed:{EscapeLuaComment(raw)}]] 0";

    /// <summary>Shared with <see cref="ParamBufferBuilder"/> so the FIRE path and the exported
    /// script parse the same inputs, negatives included (audit #5 Y2/Y5).</summary>
    internal static bool TryParseHexOrDecimal(string text, out ulong value)
    {
        value = 0;
        var t = text.Trim();
        if (t.Length == 0) return false;

        // Negative decimal -> reinterpret as ulong (sign-preserved bit pattern)
        if (t.StartsWith("-", StringComparison.Ordinal))
        {
            if (long.TryParse(t, NumberStyles.Integer, CultureInfo.InvariantCulture, out var s))
            {
                value = unchecked((ulong)s);
                return true;
            }
            return false;
        }

        if (t.StartsWith("0x", StringComparison.OrdinalIgnoreCase))
        {
            return ulong.TryParse(t.AsSpan(2), NumberStyles.HexNumber,
                                  CultureInfo.InvariantCulture, out value);
        }

        return ulong.TryParse(t, NumberStyles.Integer,
                              CultureInfo.InvariantCulture, out value);
    }

    /// <summary>Shared with <see cref="ParamBufferBuilder"/> so the FIRE path and the exported
    /// script accept the SAME spellings -- they used to disagree (audit #5 Y3).</summary>
    internal static bool? ParseBoolLiteral(string text) => text.ToLowerInvariant() switch
    {
        "true" or "1" or "yes" or "on"  => true,
        "false" or "0" or "no" or "off" => false,
        _                                => null,
    };

